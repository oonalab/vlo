/**
 * Vercel templates.
 *
 * A Vercel deployment has no long-lived process, so the host runs in `manual` dispatcher
 * mode and a cron drives `POST /v1/timers/tick`. Everything else is the same host: the
 * route file is a drop-in `app/api/vlo/[[...path]]/route.ts` around `handler()`.
 */

import type { DeployPlan, RenderedFile } from "./render.ts";

const TICK_PATH = "/api/vlo/v1/timers/tick";

export function renderVercel(plan: DeployPlan): RenderedFile[] {
  const files: RenderedFile[] = [
    { path: "vercel/route.ts", contents: route(plan) },
    { path: "vercel/env.md", contents: envChecklist(plan) },
  ];
  if (plan.roles.includes("orchestrator")) {
    files.splice(1, 0, { path: "vercel/vercel-crons.json", contents: crons(plan) });
  }
  return files;
}

export function vercelCommands(plan: DeployPlan): string[] {
  const names = envNames(plan);
  return [
    `# 1. drop the route in`,
    `mkdir -p src/app/api/vlo/\\[\\[...path\\]\\]`,
    `cp deploy/vlo/vercel/route.ts "src/app/api/vlo/[[...path]]/route.ts"`,
    ``,
    `# 2. environment (repeat for preview if you run one)`,
    ...names.map((name) => `vercel env add ${name} production`),
    ``,
    ...(plan.roles.includes("orchestrator")
      ? [
          `# 3. merge deploy/vlo/vercel/vercel-crons.json into the "crons" array in vercel.json`,
          ``,
          `# 4. ship`,
        ]
      : [`# 3. ship`]),
    `vercel deploy --prod`,
  ];
}

function route(plan: DeployPlan): string {
  const queueLines = plan.queues
    .filter((q) => q.mode === "push")
    .map(
      (q) =>
        `    ${key(q.name)}: { url: required("${envVar(q.name)}"), secret: required("VLO_PUSH_SECRET") },`,
    );

  return `/**
 * Vlo control plane — generated by \`vlo deploy --profile ${plan.profile}\`.
 * Drop in at \`app/api/vlo/[[...path]]/route.ts\`.
 *
 * Roles: ${plan.roles.join(", ")}. The dispatcher runs in \`manual\` mode because a
 * serverless function has no process to tick in — the cron in vercel-crons.json calls
 * POST /v1/timers/tick instead, and every tick does one full dispatcher pass.
 */

import { handler } from "@oona/vlo/host";
// Globs cannot be bundled into a function, so the modules are imported explicitly.
// \`vlo deploy\` found ${plan.workflows.length === 0 ? "no workflows" : `these workflows: ${plan.workflows.join(", ")}`}; re-export them from these two barrels.
import { workflows } from "@/vlo/workflows";
import { workers } from "@/vlo/workers";

// A tick and a long task push both need more than the default 10s.
export const maxDuration = 300;

function required(name: string): string {
  const value = process.env[name];
  if (value === undefined || value === "") throw new Error(\`vlo: \${name} is not set\`);
  return value;
}

export const { GET, POST } = handler({
  journal: required("DATABASE_URL"),
  blob: ${blobExpression(plan)},
  workflows,
  workers,
  roles: [${plan.roles.map((r) => `"${r}"`).join(", ")}],
  basePath: "/api/vlo",
  dispatcher: { mode: "manual" },
  queues: {
${queueLines.length === 0 ? "    // no push queues in this profile" : queueLines.join("\n")}
  },
  auth: { token: required("VLO_TOKEN"), pushSecret: required("VLO_PUSH_SECRET") },
  publicUrl: required("VLO_PUBLIC_URL"),
});
`;
}

function crons(plan: DeployPlan): string {
  return `${JSON.stringify({ crons: [{ path: TICK_PATH, schedule: plan.cron }] }, null, 2)}\n`;
}

function envChecklist(plan: DeployPlan): string {
  const rows: [string, string][] = [
    ["`DATABASE_URL`", "Postgres journal. Pooled connection string — functions are short-lived."],
    ["`VLO_TOKEN`", "Bearer token every control-plane route requires. The same value its clients hold."],
    [
      "`VLO_PUSH_SECRET`",
      "HMAC secret shared with the workers this host pushes to and accepts callbacks from.",
    ],
    [
      "`VLO_PUBLIC_URL`",
      "This deployment's own origin, e.g. `https://example.com`. Fills `complete_url` on a push.",
    ],
    ...plan.queues
      .filter((q) => q.mode === "push")
      .map((q): [string, string] => [
        `\`${envVar(q.name)}\``,
        `Push endpoint for the \`${q.name}\` queue.`,
      ]),
  ];

  if (plan.bucket !== undefined) {
    rows.push(["`VLO_BUCKET`", "Bucket holding offloaded payloads and checkpoints."]);
  }
  if (plan.blobScheme === "gcs") {
    rows.push([
      "`GCP_SERVICE_ACCOUNT_KEY_BASE64`",
      "Base64 service-account JSON for the blob bucket. Only needed off Google infrastructure — on Cloud Run, ADC covers it.",
    ]);
  }

  return `# Environment — \`${plan.profile}\` on Vercel

Set every variable below on the Vercel project before the first deploy. Vlo reads them at
request time, so a change needs a redeploy only if the value is baked into a build.

| Variable | What it is |
| --- | --- |
${rows.map(([name, description]) => `| ${name} | ${description} |`).join("\n")}

## Checks

- \`vlo doctor --profile ${plan.profile}\` with the same variables exported locally, before deploying.
${
  plan.roles.includes("orchestrator")
    ? `- The cron in \`vercel-crons.json\` (\`${plan.cron}\`) is what advances timers, retries and task
  pushes. Without it, runs start and then sit still.`
    : `- This deployment holds no \`orchestrator\` role, so something else must run the dispatcher.`
}
- Blob store: \`${plan.blobScheme}\`${plan.bucket !== undefined ? ` · bucket \`${plan.bucket}\`` : ""}.
`;
}

function envNames(plan: DeployPlan): string[] {
  return [
    "DATABASE_URL",
    "VLO_TOKEN",
    "VLO_PUSH_SECRET",
    "VLO_PUBLIC_URL",
    ...plan.queues.filter((q) => q.mode === "push").map((q) => envVar(q.name)),
    ...(plan.bucket !== undefined ? ["VLO_BUCKET"] : []),
    ...(plan.blobScheme === "gcs" ? ["GCP_SERVICE_ACCOUNT_KEY_BASE64"] : []),
  ];
}

/** A function's filesystem is ephemeral, so anything but a bucket is a dev-only fallback. */
function blobExpression(plan: DeployPlan): string {
  return plan.bucket !== undefined
    ? "`gcs://${required(\"VLO_BUCKET\")}/vlo`"
    : '"file:///tmp/vlo-blobs"';
}

function key(queue: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(queue) ? queue : JSON.stringify(queue);
}

function envVar(queue: string): string {
  return `VLO_QUEUE_${queue.replace(/[^A-Za-z0-9]/g, "_").toUpperCase()}_URL`;
}
